def find_best_model():
    """Find best model based on saved metadata."""
    print("🔍 Searching for trained models...")
    
    best_model = None
    best_mae = float('inf')
    
    models = ['baseline', 'random_forest', 'xgboost']
    
    for model_name in models:
        metadata_path = f'{MODEL_DIR}/{model_name}_metadata.txt'
        if os.path.exists(metadata_path):
            with open(metadata_path, 'r', encoding='utf-8') as f:
                metadata_str = f.read()
                # Parse metadata
                metadata = eval(metadata_str)
                mae = metadata.get('mae', float('inf'))
                
                print(f"  Found: {model_name}")
                print(f"    MAE: {mae:.4f}, RMSE: {metadata.get('rmse', 0):.4f}, MAPE: {metadata.get('mape', 0):.2f}%")
                
                if mae < best_mae:
                    best_mae = mae
                    best_model = {
                        'name': model_name,
                        'display_name': metadata.get('name', model_name),
                        'mae': mae,
                        'rmse': metadata.get('rmse', 0),
                        'mape': metadata.get('mape', 0),
                        'metadata': metadata,
                        'model_path': f'{MODEL_DIR}/{model_name}_model.pkl'
                    }
    
    if best_model:
        print()
        print(f"✅ Best model: {best_model['display_name']}")
        print(f"   Performance: MAE={best_model['mae']:.4f}, RMSE={best_model['rmse']:.4f}")
    else:
        print("❌ No trained models found")
        return None
    
    return best_model

