    try:
        # Check if ML service is running
        health_url = f"{ML_SERVICE_URL}/health"
        response = requests.get(health_url, timeout=5)
        
        if response.status_code == 200:
            print(f"  ✅ ML Service is running on {ML_SERVICE_URL}")
            health_data = response.json()
            print(f"     Status: {health_data.get('status', 'unknown')}")
        else:
            print(f"  ⚠️ ML Service returned status {response.status_code}")
    except requests.exceptions.ConnectionError:
        print(f"  ⚠️ Cannot connect to ML Service at {ML_SERVICE_URL}")
        print("     Make sure ml-service is running (see deployment instructions)")
    except Exception as e:
        print(f"  ⚠️ Error testing API: {e}")

